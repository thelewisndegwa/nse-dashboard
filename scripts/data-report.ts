/**
 * Writes nse-data/quality-report.md: what the loader cleaned out of the daily files,
 * the splits and bonuses it applies, and the price jumps it could not explain.
 *
 *   npm run data-report
 */
import fs from "fs";
import path from "path";
import { DATA_DIR, getMarket, ymdToIso, type Series } from "../lib/history";

const market = getMarket();
const stocks = market.list.filter((series) => !series.index);
const listedSince = market.end - 10000;

function price(n: number): string {
  return n >= 100 ? n.toFixed(2) : n.toPrecision(4);
}

function pct(from: number, to: number): string {
  const change = (to / from - 1) * 100;
  return `${change > 0 ? "+" : ""}${change.toFixed(0)}%`;
}

function status(series: Series): string {
  const last = series.dates[series.dates.length - 1];
  return last >= listedSince ? "" : ` (last traded ${ymdToIso(last)})`;
}

const dropped = market.list.reduce(
  (sum, series) => ({
    weekend: sum.weekend + series.dropped.weekend,
    duplicate: sum.duplicate + series.dropped.duplicate,
    spike: sum.spike + series.dropped.spike,
  }),
  { weekend: 0, duplicate: 0, spike: 0 }
);
const sessions = market.list.reduce((sum, series) => sum + series.dates.length, 0);

const lines: string[] = [];
lines.push("# Daily data quality report", "");
lines.push(`Generated by \`npm run data-report\` from ${market.files.length} files in \`nse-data/\`.`, "");
lines.push(`- Sessions kept: ${sessions.toLocaleString("en-US")} across ${market.list.length} tickers, ${ymdToIso(market.start)} to ${ymdToIso(market.end)}.`);
lines.push(`- Dropped: ${dropped.weekend} weekend rows, ${dropped.duplicate} duplicate rows, ${dropped.spike} short spikes that reverted.`);
lines.push(
  `- Skipped: ${market.skipped.rights} rights-issue rows, ${market.skipped.unreadable} unreadable rows, ${market.skipped.outOfYear} rows dated outside their file's year.`
);
lines.push("");

lines.push("## Splits and bonus issues applied", "");
lines.push("Found where the Adjust column steps down and the traded price falls by about the same ratio.", "");
lines.push("| Ticker | Ex-date | Action | Close before | Close after |", "| --- | --- | --- | --- | --- |");
for (const series of stocks) {
  for (const action of series.actions) {
    lines.push(
      `| ${series.code}${status(series)} | ${ymdToIso(action.date)} | ${action.label} | ${price(action.closeBefore)} | ${price(action.closeAfter)} |`
    );
  }
}
lines.push("");

lines.push("## Adjust-column steps not applied", "");
lines.push("The Adjust column changed here but the traded price did not move by the same ratio, so nothing was applied.", "");
lines.push("| Ticker | Session | Close before | Close after |", "| --- | --- | --- | --- |");
for (const series of stocks) {
  for (const step of series.unconfirmed) {
    lines.push(`| ${series.code}${status(series)} | ${ymdToIso(step.date)} | ${price(step.from)} | ${price(step.to)} |`);
  }
}
lines.push("");

lines.push("## Unexplained price jumps", "");
lines.push(
  "Moves bigger than 1.25x between sessions (a rise of over 25% or a fall of over 20%) with no split or bonus behind them. NSE limits a day's move to about 10%, so these are usually an unrecorded corporate action, a long suspension, or a bad row. The what-if page warns when a holding period crosses one.",
  ""
);
lines.push("| Ticker | From | To | Close | Change |", "| --- | --- | --- | --- | --- |");
for (const series of stocks) {
  for (const jump of series.jumps) {
    lines.push(
      `| ${series.code}${status(series)} | ${ymdToIso(jump.prevDate)} | ${ymdToIso(jump.date)} | ${price(jump.from)} -> ${price(jump.to)} | ${pct(jump.from, jump.to)} |`
    );
  }
}
lines.push("");

const out = path.join(DATA_DIR, "quality-report.md");
fs.writeFileSync(out, lines.join("\n"));

const actionCount = stocks.reduce((sum, series) => sum + series.actions.length, 0);
const jumpCount = stocks.reduce((sum, series) => sum + series.jumps.length, 0);
console.log(`${ymdToIso(market.start)} to ${ymdToIso(market.end)}: ${sessions} sessions, ${market.list.length} tickers`);
console.log(`dropped ${JSON.stringify(dropped)}, skipped ${JSON.stringify(market.skipped)}`);
console.log(`${actionCount} splits/bonuses applied, ${jumpCount} unexplained jumps`);
console.log(`wrote ${path.relative(process.cwd(), out)}`);
